// ---- ui/public/ assets (browser, PWA, OG) --------------------------------------------
// Raster icons are generated from the pitch app icon SVG so every size stays aligned.
// Committed to public/ so the offline demo serves them without a rasteriser at runtime.

const appIconSvg = FILES.find(([n]) => n === 'docket-icon-pitch.svg')[1];
const faviconSvg = FILES.find(([n]) => n === 'docket-favicon-pitch.svg')[1];
const ogSvg = FILES.find(([n]) => n === 'docket-social-og.svg')[1];

await mkdir(PUBLIC_DIR, { recursive: true });
await writeFile(path.join(PUBLIC_DIR, 'favicon.svg'), faviconSvg);

const PNG_EXPORTS = [
  ['favicon-16.png', appIconSvg, 16],
  ['favicon-32.png', appIconSvg, 32],
  ['apple-touch-icon.png', appIconSvg, 180],
  ['icon-192.png', appIconSvg, 192],
  ['icon-512.png', appIconSvg, 512],
  ['icon-1024.png', appIconSvg, 1024],
  ['og-image.png', ogSvg, { width: 1200, height: 630 }],
];

for (const [name, svgContent, size] of PNG_EXPORTS) {
  const pipeline = sharp(Buffer.from(svgContent));
  const out = typeof size === 'number'
    ? pipeline.resize(size, size)
    : pipeline.resize(size.width, size.height);
  await out.png().toFile(path.join(PUBLIC_DIR, name));
}

