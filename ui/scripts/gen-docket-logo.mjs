#!/usr/bin/env node
// Generate every Docket Bracket mark SVG under ui/src/brand/logo/docket/ from one
// geometry definition, so the 24 variants cannot drift. Run via `npm run gen:logo`.
// Spec: ui/src/brand/DOCKET-LOGO.md. Adopted 2026-09-12.
//
// Colors are brand v3.0 tokens only (see ui/src/brand/tokens.css). Logo files are
// allowed to name hex values directly — the same exception as tokens.css and the
// OffGrid handoff SVGs in ui/src/brand/logo/.

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.resolve(HERE, '..', 'src', 'brand', 'logo', 'docket');
const PUBLIC_DIR = path.resolve(HERE, '..', 'public');

const C = {
  pitch: '#1B1813',
  bone: '#F1ECE0',
  ground: '#F7F4EC',
  raised: '#FBF9F3',
  sand: '#D9C9A8',
  ink: '#1B1813',
  ember: '#FF6A00',
  dim: '#9A9082',
};

const MARK_SIZE = 200;
const WORDMARK = 'Docket';
const WORDMARK_TRACKING_EM = -0.04;
/** Matches OffGrid horizontal lockup (`wordmark.svg`: 240 − 196). */
const HORIZONTAL_GAP = 44;
/** Space from mark bottom to wordmark cap height in stacked lockups. */
const STACKED_GAP = 40;
/** Space between title and subtitle in social artboards. */
const SUBTITLE_GAP = 20;
const FONT = 'Instrument Sans, system-ui, sans-serif';

/** Bracket arms in the 200x200 artboard. Do not edit per-file; edit here. */
const BRACKET_ARMS = [
  [44, 44, 48, 16], [44, 44, 16, 48],
  [108, 44, 48, 16], [140, 44, 16, 48],
  [44, 140, 48, 16], [44, 108, 16, 48],
  [108, 140, 48, 16], [140, 108, 16, 48],
];
const CENTER = [76, 76, 48, 48];

const BANNER = `<!-- GENERATED by ui/scripts/gen-docket-logo.mjs — do not edit.
     Run \`npm run gen:logo\`. Product mark for docket (distinct from OffGrid
     mark-ember.svg). Geometry and usage: ui/src/brand/DOCKET-LOGO.md. -->`;

function rect(x, y, w, h, fill) {
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}"></rect>`;
}

function mark(bracket, center) {
  const arms = BRACKET_ARMS.map(([x, y, w, h]) => rect(x, y, w, h, bracket)).join('\n  ');
  const [cx, cy, cw, ch] = CENTER;
  return `${arms}\n  ${rect(cx, cy, cw, ch, center)}`;
}

function svg({ viewBox, width, height, title, body }) {
  const dims = width && height ? ` width="${width}" height="${height}"` : '';
  return `<?xml version="1.0"?>\n${BANNER}\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${dims} role="img" aria-label="Docket">\n  <title>${title}</title>\n${body}\n</svg>\n`;
}

function wordmarkText({
  x,
  y,
  size,
  fill,
  anchor,
  middle = false,
  text = WORDMARK,
}) {
  const anchorAttr = anchor ? ` text-anchor="${anchor}"` : '';
  const baseline = middle ? ' dominant-baseline="middle"' : '';
  const tracking = (size * WORDMARK_TRACKING_EM).toFixed(2);
  return `  <text x="${x}" y="${y}"${anchorAttr}${baseline} font-family="${FONT}" font-weight="400" font-size="${size}" letter-spacing="${tracking}" fill="${fill}">${text}</text>`;
}

function subtitleText({ x, y, size, fill, anchor, text }) {
  const anchorAttr = anchor ? ` text-anchor="${anchor}"` : '';
  const tracking = (size * WORDMARK_TRACKING_EM).toFixed(2);
  return `  <text x="${x}" y="${y}"${anchorAttr} dominant-baseline="middle" font-family="${FONT}" font-weight="400" font-size="${size}" letter-spacing="${tracking}" fill="${fill}">${text}</text>`;
}

function markGroup({ x, y, scale, bracket, center }) {
  const rendered = MARK_SIZE * scale;
  return {
    rendered,
    right: x + rendered,
    bottom: y + rendered,
    svg: `  <g transform="translate(${x} ${y}) scale(${scale})">\n    ${mark(bracket, center)}\n  </g>`,
  };
}

function textBlock({ x, centerY, anchor, titleSize, titleFill, subtitle }) {
  if (!subtitle) {
    return wordmarkText({ x, y: centerY, size: titleSize, fill: titleFill, anchor, middle: true });
  }
  const block = titleSize + SUBTITLE_GAP + subtitle.size;
  const titleY = centerY - block / 2 + titleSize / 2;
  const subtitleY = centerY + block / 2 - subtitle.size / 2;
  return [
    wordmarkText({ x, y: titleY, size: titleSize, fill: titleFill, anchor, middle: true }),
    subtitleText({ x, y: subtitleY, size: subtitle.size, fill: subtitle.fill, anchor, text: subtitle.text }),
  ].join('\n');
}

function stackedColumn({ width, height, markScale, titleSize, subtitle, bg, bracket, center, textFill }) {
  const markRendered = MARK_SIZE * markScale;
  const subtitleBlock = subtitle ? SUBTITLE_GAP + subtitle.size : 0;
  const columnHeight = markRendered + STACKED_GAP + titleSize + subtitleBlock;
  const markY = (height - columnHeight) / 2;
  const markX = (width - markRendered) / 2;
  const bgRect = bg ? `  <rect width="${width}" height="${height}" fill="${bg}"></rect>\n` : '';
  const placed = markGroup({ x: markX, y: markY, scale: markScale, bracket, center });
  const lines = [
    placed.svg,
    wordmarkText({
      x: width / 2,
      y: markY + markRendered + STACKED_GAP + titleSize / 2,
      size: titleSize,
      fill: textFill,
      anchor: 'middle',
      middle: true,
    }),
  ];
  if (subtitle) {
    lines.push(subtitleText({
      x: width / 2,
      y: markY + markRendered + STACKED_GAP + titleSize + SUBTITLE_GAP + subtitle.size / 2,
      size: subtitle.size,
      fill: subtitle.fill,
      anchor: 'middle',
      text: subtitle.text,
    }));
  }
  return `${bgRect}${lines.join('\n')}`;
}

function squareIcon(title, bg, bracket, center) {
  const bgRect = bg ? `  <rect width="200" height="200" fill="${bg}"></rect>\n` : '';
  return svg({
    viewBox: '0 0 200 200',
    width: 200,
    height: 200,
    title,
    body: `${bgRect}  ${mark(bracket, center).replace(/\n/g, '\n  ')}`,
  });
}

function favicon(title, bg, bracket, center) {
  return svg({
    viewBox: '0 0 32 32',
    width: 32,
    height: 32,
    title,
    body: `  <rect width="32" height="32" fill="${bg}"></rect>\n  <g transform="translate(0 0) scale(0.16)">\n    ${mark(bracket, center)}\n  </g>`,
  });
}

function lockupHorizontal(title, bg, bracket, center, textFill) {
  const width = 600;
  const height = 200;
  const scale = 0.84;
  const rendered = MARK_SIZE * scale;
  const markX = 16;
  const markY = (height - rendered) / 2;
  const textX = markX + rendered + HORIZONTAL_GAP;
  const textSize = 88;
  const bgRect = bg ? `  <rect width="${width}" height="${height}" fill="${bg}"></rect>\n` : '';
  const placed = markGroup({ x: markX, y: markY, scale, bracket, center });
  return svg({
    viewBox: `0 0 ${width} ${height}`,
    width,
    height,
    title,
    body: `${bgRect}${placed.svg}\n${wordmarkText({
      x: textX,
      y: height / 2,
      size: textSize,
      fill: textFill,
      middle: true,
    })}`,
  });
}

function lockupStacked(title, bg, bracket, center, textFill) {
  const width = 400;
  const height = 480;
  return svg({
    viewBox: `0 0 ${width} ${height}`,
    width,
    height,
    title,
    body: stackedColumn({
      width,
      height,
      markScale: 1,
      titleSize: 72,
      bg,
      bracket,
      center,
      textFill,
    }),
  });
}

function wideSocial({
  viewBox,
  width,
  height,
  title,
  bg,
  layout,
  markScale,
  textLines,
}) {
  let body;
  if (layout === 'row') {
    const { markX, gap, titleSize, subtitle } = textLines;
    const rendered = MARK_SIZE * markScale;
    const markY = (height - rendered) / 2;
    const textX = markX + rendered + gap;
    const placed = markGroup({ x: markX, y: markY, scale: markScale, bracket: C.ember, center: C.bone });
    body = `  <rect width="${width}" height="${height}" fill="${bg}"></rect>\n${placed.svg}\n${textBlock({
      x: textX,
      centerY: height / 2,
      titleSize,
      titleFill: C.bone,
      subtitle,
    })}`;
  } else {
    body = `  <rect width="${width}" height="${height}" fill="${bg}"></rect>\n${stackedColumn({
      width,
      height,
      markScale,
      titleSize: textLines.titleSize,
      subtitle: textLines.subtitle,
      bg: null,
      bracket: C.ember,
      center: C.bone,
      textFill: C.bone,
    })}`;
  }

  return svg({ viewBox, width, height, title, body });
}

